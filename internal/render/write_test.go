package render

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/aashish-thapa/dc2kit/internal/convert"
	"github.com/aashish-thapa/dc2kit/internal/devcontainer"
	"github.com/aashish-thapa/dc2kit/internal/feature"
)

func sampleKit() Kit {
	return Kit{
		Stem:       "app",
		Descriptor: []byte("schemaVersion: \"3\"\n"),
		Dockerfile: "FROM x\n",
		Features: []convert.FeatureStep{{
			Dir:        "01-node",
			Ref:        "ghcr.io/x/node:1",
			InstallEnv: []devcontainer.EnvVar{{Name: "VERSION", Value: "it's 22"}},
			Files:      []feature.File{{Path: "lib/helper.sh", Mode: 0o755, Data: []byte("x")}},
		}},
	}
}

func TestWriteLaysOutTheKit(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "kit")
	if err := Write(dir, sampleKit(), false); err != nil {
		t.Fatal(err)
	}
	for _, p := range []string{"app.yaml", "app.dockerfile", floorScript, marker, "features/01-node/lib/helper.sh"} {
		if _, err := os.Stat(filepath.Join(dir, p)); err != nil {
			t.Errorf("missing %s", p)
		}
	}
	env, _ := os.ReadFile(filepath.Join(dir, "features/01-node", featureEnvFile))
	if string(env) != "VERSION='it'\\''s 22'\n" {
		t.Fatalf("env file = %q", env)
	}
}

func TestWriteNeverClobbersForeignDirectories(t *testing.T) {
	dir := t.TempDir()
	keep := filepath.Join(dir, "important.txt")
	if err := os.WriteFile(keep, []byte("mine"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Write(dir, sampleKit(), false); err == nil {
		t.Fatal("a non-empty directory must be refused without --force")
	}
	if err := Write(dir, sampleKit(), true); err == nil || !strings.Contains(err.Error(), "not generated by dc2kit") {
		t.Fatalf("--force must refuse a directory without the marker, got %v", err)
	}
	if _, err := os.Stat(keep); err != nil {
		t.Fatal("the foreign file was removed")
	}
}

func TestForceRegenerationDropsStaleFeatures(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "kit")
	if err := Write(dir, sampleKit(), false); err != nil {
		t.Fatal(err)
	}
	k := sampleKit()
	k.Features[0].Dir = "01-python"
	if err := Write(dir, k, true); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "features/01-node")); !os.IsNotExist(err) {
		t.Fatal("a feature removed from devcontainer.json must not linger in the kit")
	}
}
