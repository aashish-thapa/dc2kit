//go:embed sbx-floor.sh
var floorScriptBody []byte

// marker identifies a directory dc2kit generated, so --force never deletes
// a directory someone else owns.
const marker = ".dc2kit"

// Kit is a rendered kit ready to write.
type Kit struct {
	Stem       string
	Descriptor []byte
	Dockerfile string
	Features   []convert.FeatureStep
}

// Write lays the kit out. Existing output is replaced only when overwrite
// is set and dc2kit's marker shows dc2kit wrote it; in-context, the
// project's own files beside the descriptor are never touched.
func Write(layout Layout, k Kit, overwrite bool) error {
	dir := layout.kitDir()
	descriptorPath := layout.descriptorPath(k.Stem)
	if err := prepare(layout, descriptorPath, overwrite); err != nil {
		return err
	}
	files := map[string][]byte{
		filepath.Join(dir, marker):               []byte("generated by dc2kit; regenerate rather than edit\n"),
		descriptorPath:                           k.Descriptor,
		filepath.Join(dir, k.Stem+".dockerfile"): []byte(k.Dockerfile),
		filepath.Join(dir, floorScript):          floorScriptBody,
	}
	for name, data := range files {
		if err := os.WriteFile(name, data, 0o644); err != nil {
			return err
		}
	}
	for _, step := range k.Features {
		if err := writeFeature(filepath.Join(dir, featuresDir, step.Dir), step); err != nil {
			return fmt.Errorf("write feature %s: %w", step.Ref, err)
		}
	}
	return nil
}

func prepare(layout Layout, descriptorPath string, overwrite bool) error {
	dir := layout.kitDir()
	entries, err := os.ReadDir(dir)
	exists := err == nil && len(entries) > 0
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	_, markerErr := os.Stat(filepath.Join(dir, marker))
	isOurs := markerErr == nil

	if layout.IsInContext() {
		if _, err := os.Stat(descriptorPath); err == nil && !isOurs {
			return fmt.Errorf("%s already exists and %s has no %s marker; refusing to overwrite it", descriptorPath, dir, marker)
		}
	}
	switch {
	case !exists:
		return os.MkdirAll(dir, 0o755)
	case !overwrite:
		return fmt.Errorf("%s is not empty; pass --force to regenerate a dc2kit output directory", dir)
	case !isOurs:
		return fmt.Errorf("%s was not generated by dc2kit (no %s marker); refusing to overwrite it", dir, marker)
	}
	// Feature folders are removed so a dropped feature does not linger.
	return os.RemoveAll(filepath.Join(dir, featuresDir))
}

func writeFeature(dir string, step convert.FeatureStep) error {
	for _, f := range step.Files {
		target := filepath.Join(dir, filepath.FromSlash(f.Path))
		if !strings.HasPrefix(target, dir+string(filepath.Separator)) {
			return fmt.Errorf("payload path %q escapes the feature directory", f.Path)
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, f.Data, f.Mode|0o600); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(dir, featureEnvFile), []byte(envFile(step.InstallEnv)), 0o644)
}

// envFile renders option values as a file install.sh sources with `set -a`.
func envFile(env []devcontainer.EnvVar) string {
	var b strings.Builder
	for _, v := range env {
		b.WriteString(v.Name + "=" + shell.Quote(v.Value) + "\n")
	}
	return b.String()
}
