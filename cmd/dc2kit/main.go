// Command dc2kit converts a devcontainer.json into a Docker Sandboxes kit.
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/aashish-thapa/dc2kit/internal/convert"
	"github.com/aashish-thapa/dc2kit/internal/devcontainer"
	"github.com/aashish-thapa/dc2kit/internal/feature"
	"github.com/aashish-thapa/dc2kit/internal/kit"
	"github.com/aashish-thapa/dc2kit/internal/render"
)

func main() {
	if err := run(os.Args[1:], os.Stdout, os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, "dc2kit:", err)
		os.Exit(1)
	}
}

type cliFlags struct {
	out           string
	name          string
	baseImage     string
	sourceURL     string
	installEgress string
	allow         multiFlag
	force         bool
	timeout       time.Duration
}

type multiFlag []string

func (m *multiFlag) String() string     { return strings.Join(*m, ",") }
func (m *multiFlag) Set(v string) error { *m = append(*m, v); return nil }

func run(args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("dc2kit", flag.ContinueOnError)
	fs.SetOutput(stderr)
	var f cliFlags
	fs.StringVar(&f.out, "o", "sbx-kit", "output directory for the kit")
	fs.StringVar(&f.name, "name", "", "kit file stem (default: derived from the devcontainer name)")
	fs.StringVar(&f.baseImage, "base-image", "", "image to build FROM instead of devcontainer.json's (required for \"build\" configs)")
	fs.StringVar(&f.sourceURL, "source-url", "", "sourceUrl to record in the descriptor")
	fs.StringVar(&f.installEgress, "install-egress", "open", "install-phase egress: \"open\" or \"presets\"")
	fs.Var(&f.allow, "allow", "extra runtime egress host (repeatable)")
	fs.BoolVar(&f.force, "force", false, "regenerate an existing dc2kit output directory")
	fs.DurationVar(&f.timeout, "timeout", 2*time.Minute, "time limit for fetching features")
	fs.Usage = func() {
		fmt.Fprintln(stderr, "usage: dc2kit [flags] [devcontainer.json | project dir]")
		fs.PrintDefaults()
	}
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() > 1 {
		fs.Usage()
		return errors.New("expected at most one path")
	}
	target := "."
	if fs.NArg() == 1 {
		target = fs.Arg(0)
	}

	egress, err := parseInstallEgress(f.installEgress)
	if err != nil {
		return err
	}
	configPath, err := findConfig(target)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return err
	}
	cfg, err := devcontainer.Parse(raw)
	if err != nil {
		return err
	}

	ctx, cancel := context.WithTimeout(context.Background(), f.timeout)
	defer cancel()
	resolver := feature.SourceResolver{
		Local:    feature.LocalResolver{ConfigDir: filepath.Dir(configPath)},
		Registry: feature.RegistryResolver{},
	}
	features, err := resolveFeatures(ctx, resolver, cfg, stderr)
	if err != nil {
		return err
	}

	plan, report, err := convert.Convert(convert.Input{
		Config:   cfg,
		Features: features,
		Options: convert.Options{
			BaseImage:     f.baseImage,
			RuntimeAllow:  f.allow,
			InstallEgress: egress,
			SourceURL:     f.sourceURL,
		},
	})
	printReport(stderr, report)
	if err != nil {
		return err
	}

	provenance := "Generated by dc2kit from " + filepath.ToSlash(configPath) + ". Regenerate rather than edit."
	descriptor, err := kit.Marshal(plan.Descriptor, provenance)
	if err != nil {
		return err
	}
	warnings, err := kit.Validate(ctx, descriptor)
	if err != nil {
		return fmt.Errorf("generated descriptor fails the kit spec (this is a dc2kit bug, please report it): %w", err)
	}
	for _, w := range warnings {
		fmt.Fprintln(stderr, "spec warning:", w)
	}

	stem := f.name
	if stem == "" {
		stem = slug(cfg.Name)
	}
	if err := render.Write(f.out, render.Kit{
		Stem:       stem,
		Descriptor: descriptor,
		Dockerfile: render.Dockerfile(plan.Image, provenance),
		Features:   plan.Image.Features,
	}, f.force); err != nil {
		return err
	}
	printNextSteps(stdout, f.out, stem)
	return nil
}

func parseInstallEgress(v string) (convert.InstallEgress, error) {
	switch v {
	case "open":
		return convert.InstallEgressOpen, nil
	case "presets":
		return convert.InstallEgressPresets, nil
	default:
		return 0, fmt.Errorf("--install-egress must be \"open\" or \"presets\", got %q", v)
	}
}

// findConfig accepts a devcontainer.json path or a project directory, and
// looks in the locations the devcontainer spec defines.
func findConfig(target string) (string, error) {
	info, err := os.Stat(target)
	if err != nil {
		return "", err
	}
	if !info.IsDir() {
		return target, nil
	}
	for _, candidate := range []string{
		filepath.Join(target, ".devcontainer", "devcontainer.json"),
		filepath.Join(target, ".devcontainer.json"),
	} {
		if _, err := os.Stat(candidate); err == nil {
			return candidate, nil
		}
	}
	nested, _ := filepath.Glob(filepath.Join(target, ".devcontainer", "*", "devcontainer.json"))
	switch len(nested) {
	case 0:
		return "", fmt.Errorf("no devcontainer.json under %s", target)
	case 1:
		return nested[0], nil
	default:
		return "", fmt.Errorf("several devcontainer configs under %s; pass one: %s", target, strings.Join(nested, ", "))
	}
}

func resolveFeatures(ctx context.Context, r feature.Resolver, cfg devcontainer.Config, stderr io.Writer) ([]feature.Feature, error) {
	resolved := make([]feature.Feature, 0, len(cfg.Features))
	for _, req := range cfg.Features {
		fmt.Fprintf(stderr, "fetching feature %s\n", req.Ref)
		f, err := r.Resolve(ctx, req)
		if err != nil {
			return nil, err
		}
		resolved = append(resolved, f)
	}
	return feature.Order(resolved, cfg.OverrideFeatureInstallOrder)
}

func printReport(w io.Writer, report convert.Report) {
	for _, f := range report.Findings {
		fmt.Fprintf(w, "%-4s  %s: %s\n", f.Level, f.Field, f.Message)
	}
}

func printNextSteps(w io.Writer, dir, stem string) {
	// sbx reads a bare name as a registry reference; a local kit needs a
	// path that starts with "/" or ".".
	dir = filepath.ToSlash(filepath.Clean(dir))
	if !strings.HasPrefix(dir, "/") && !strings.HasPrefix(dir, ".") {
		dir = "./" + dir
	}
	fmt.Fprintf(w, `
Kit written to %[1]s/

Build it (needs a docker-container builder so the kit annotations survive):
  docker buildx create --name kit-builder --driver docker-container --bootstrap
  docker buildx build --builder kit-builder -f %[1]s/%[2]s.yaml -t %[2]s:dev %[1]s/

Run it with an agent:
  BUILDX_BUILDER=kit-builder sbx run --name %[2]s %[1]s --kit docker/sbx-kit-claude-mixin:<version> .
`, dir, stem)
}

var nonSlug = regexp.MustCompile(`[^a-z0-9]+`)

func slug(name string) string {
	s := strings.Trim(nonSlug.ReplaceAllString(strings.ToLower(name), "-"), "-")
	if s == "" {
		return "devcontainer"
	}
	return s
}
